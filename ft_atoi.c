#include "libft.h"

int	ft_atoi(const char *n)
{
	int	i;
	int	sign;
	int	res;

	(1) && (i = 0, sign = 1, res = 0);
	while ((n[i] >= 9 && n[i] <= 13) || n[i] == ' ')
		i++;
	if (n[i] == '+' || n[i] == '-')
	{
		if (n[i] == '-')
			sign *= -1;
		i++;
	}
	while (n[i] >= '0' && n[i] <= '9')
		res = res * 10 + (n[i++] - 48);
	return (sign * res);
}
